import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const outputPath = join(root, "static", "THIRD_PARTY_LICENSES.txt");
const packageLock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
const packageJson = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

const components = [];
const licenseTexts = new Map();
const missingLicenseTexts = [];

collectNpmComponents();
collectCargoComponents();
collectCodeBuster();
const unknownLicenses = components.filter((component) => component.license === "UNKNOWN");
if (unknownLicenses.length > 0) {
  throw new Error(`Missing license metadata for: ${unknownLicenses.map(({ id }) => id).join(", ")}`);
}


components.sort((left, right) => compare(left.id, right.id));
for (const group of licenseTexts.values()) group.usedBy.sort(compare);

const mplComponents = components.filter((component) => component.license.includes("MPL-2.0"));
const lines = [
  "THIRD-PARTY SOFTWARE NOTICES",
  "============================",
  "",
  "Spaghetti Meter includes the open-source components listed below. The applicable",
  "copyright notices and license terms follow the component inventory.",
  "",
  "This file is generated by scripts/generate-third-party-notices.mjs from",
  "package-lock.json, Cargo.lock/Cargo metadata, installed package license files,",
  "and the pinned Code Buster notice. Do not edit it by hand.",
  "",
  "Cargo resolves dependencies for every configured desktop target. A component",
  "listed here may therefore be absent from a particular platform's executable.",
  "",
];

if (mplComponents.length > 0) {
  lines.push(
    "MPL-2.0 SOURCE AVAILABILITY",
    "---------------------------",
    "Spaghetti Meter uses the following MPL-2.0 components without modifying their source.",
    "Their exact Source Code Form can be downloaded at no charge from the URLs below:",
    ...mplComponents.map((component) => `- ${component.id}: ${component.sourceArchive}`),
    "",
  );
}

lines.push("COMPONENT INVENTORY", "-------------------");
for (const component of components) {
  lines.push(`- ${component.id}`, `  License: ${component.license}`, `  Source: ${component.source}`);
  if (component.authors) lines.push(`  Authors: ${component.authors}`);
}
lines.push("");

if (missingLicenseTexts.length > 0) {
  lines.push(
    "COMPONENTS WITHOUT A SEPARATE PACKAGED LICENSE FILE",
    "---------------------------------------------------",
    "For these components, the package manifest declares the license shown in the",
    "inventory, but the published package contains no separate license text. Their",
    "authors and exact source locations are retained above; the standard license",
    "terms also appear below through other components using the same licenses.",
    ...missingLicenseTexts.sort(compare).map((component) => `- ${component}`),
    "",
  );
}

lines.push("LICENSE AND NOTICE TEXTS", "------------------------", "");
const groups = [...licenseTexts.values()].sort((left, right) => compare(left.usedBy[0], right.usedBy[0]));
for (const [index, group] of groups.entries()) {
  lines.push(
    `Notice ${index + 1}`,
    `Used by: ${group.usedBy.join(", ")}`,
    "",
    group.text.trimEnd(),
    "",
    "--------------------------------------------------------------------------------",
    "",
  );
}

const output = `${lines.join("\n").trimEnd()}\n`;
if (process.argv.includes("--check")) {
  const existing = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  if (existing !== output) {
    console.error(`${relative(root, outputPath)} is stale; run npm run licenses:generate`);
    process.exitCode = 1;
  } else {
    console.log(`${relative(root, outputPath)} is current`);
  }
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, output);
  console.log(`Wrote ${relative(root, outputPath)} with ${components.length} components and ${groups.length} unique notices`);
}

function collectNpmComponents() {
  for (const [packagePath, lockEntry] of Object.entries(packageLock.packages)) {
    if (!packagePath.startsWith("node_modules/") || lockEntry.dev === true) continue;

    const packageDirectory = join(root, packagePath);
    const manifest = JSON.parse(readFileSync(join(packageDirectory, "package.json"), "utf8"));
    const name = manifest.name ?? packagePath.slice("node_modules/".length);
    const version = manifest.version ?? lockEntry.version;
    const id = `npm:${name}@${version}`;
    const source = lockEntry.resolved ?? repositoryUrl(manifest.repository) ?? manifest.homepage ?? `https://www.npmjs.com/package/${name}/v/${version}`;
    const component = {
      id,
      license: manifest.license ?? lockEntry.license ?? "UNKNOWN",
      source,
      authors: npmAuthors(manifest),
      sourceArchive: source,
    };
    components.push(component);
    addLicenseFiles(component, packageDirectory, manifest.licenseFile);
  }
}

function collectCargoComponents() {
  const metadata = JSON.parse(execFileSync(
    "cargo",
    ["metadata", "--manifest-path", "src-tauri/Cargo.toml", "--format-version", "1", "--locked"],
    { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  ));
  const nodes = new Map(metadata.resolve.nodes.map((node) => [node.id, node]));
  const reachable = new Set([metadata.resolve.root]);
  const queue = [metadata.resolve.root];

  while (queue.length > 0) {
    const node = nodes.get(queue.shift());
    for (const dependency of node?.deps ?? []) {
      const isRuntimeDependency = dependency.dep_kinds.some(({ kind }) => kind === null);
      if (!isRuntimeDependency || reachable.has(dependency.pkg)) continue;
      reachable.add(dependency.pkg);
      queue.push(dependency.pkg);
    }
  }

  for (const cargoPackage of metadata.packages) {
    if (cargoPackage.id === metadata.resolve.root || !reachable.has(cargoPackage.id)) continue;

    const cratePage = `https://crates.io/crates/${cargoPackage.name}/${cargoPackage.version}`;
    const component = {
      id: `cargo:${cargoPackage.name}@${cargoPackage.version}`,
      license: cargoPackage.license ?? "UNKNOWN",
      source: cargoPackage.repository ? `${cratePage} (${cargoPackage.repository})` : cratePage,
      authors: cargoPackage.authors.join(", "),
      sourceArchive: `https://crates.io/api/v1/crates/${cargoPackage.name}/${cargoPackage.version}/download`,
    };
    components.push(component);
    addLicenseFiles(component, dirname(cargoPackage.manifest_path), cargoPackage.license_file);
  }
}

function collectCodeBuster() {
  const version = packageJson.config.codeBusterVersion;
  const component = {
    id: `bundled:code-buster@${version}`,
    license: "MIT",
    source: `https://github.com/tool-bunker/code-buster/releases/tag/v${version}`,
    authors: "Jonas Robertsson",
    sourceArchive: `https://github.com/tool-bunker/code-buster/archive/refs/tags/v${version}.tar.gz`,
  };
  components.push(component);
  addLicenseText(component.id, readFileSync(join(root, "src-tauri", "resources", "code-buster-LICENSE.txt"), "utf8"));
}

function addLicenseFiles(component, packageDirectory, declaredLicenseFile) {
  const paths = new Set();
  if (declaredLicenseFile) {
    const declaredPath = isAbsolute(declaredLicenseFile)
      ? declaredLicenseFile
      : resolve(packageDirectory, declaredLicenseFile);
    if (existsSync(declaredPath) && statSync(declaredPath).isFile()) paths.add(declaredPath);
  }

  for (const entry of readdirSync(packageDirectory)) {
    const path = join(packageDirectory, entry);
    if (/^(licen[sc]e|copying|notice)(\.|-|$)/i.test(entry) && statSync(path).isFile()) paths.add(path);
  }

  if (paths.size === 0) {
    missingLicenseTexts.push(component.id);
    return;
  }

  for (const path of [...paths].sort(compare)) {
    addLicenseText(`${component.id} (${basename(path)})`, readFileSync(path, "utf8"));
  }
}

function addLicenseText(component, rawText) {
  const text = rawText.replaceAll("\r\n", "\n").trim();
  const hash = createHash("sha256").update(text).digest("hex");
  const existing = licenseTexts.get(hash);
  if (existing) {
    existing.usedBy.push(component);
  } else {
    licenseTexts.set(hash, { text, usedBy: [component] });
  }
}

function repositoryUrl(repository) {
  if (typeof repository === "string") return repository;
  return repository?.url;
}

function npmAuthors(manifest) {
  const values = [];
  if (typeof manifest.author === "string") values.push(manifest.author);
  else if (manifest.author?.name) values.push(manifest.author.name);
  for (const contributor of manifest.contributors ?? []) {
    if (typeof contributor === "string") values.push(contributor);
    else if (contributor?.name) values.push(contributor.name);
  }
  return [...new Set(values)].join(", ");
}

function compare(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

